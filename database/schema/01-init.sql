-- Tabla de CAIs (con columna generada PostGIS)
CREATE TABLE IF NOT EXISTS auth_user.cai (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(50) NOT NULL UNIQUE,
    nombre varchar(120) NOT NULL,
    direccion varchar(150),
    telefono varchar(20),
    localidad varchar(80),
    latitud double precision NOT NULL,
    longitud double precision NOT NULL,
    geom geography(Point,4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitud, latitud), 4326)::geography) STORED,
    activo boolean NOT NULL DEFAULT true,
    source_object_id bigint,
    fecha_sincronizacion timestamp,
    created_at timestamp NOT NULL DEFAULT NOW(),
    updated_at timestamp NOT NULL DEFAULT NOW()
);

-- Índices espaciales y de texto
CREATE INDEX IF NOT EXISTS idx_cai_geom ON auth_user.cai USING gist (geom);
CREATE INDEX IF NOT EXISTS idx_cai_localidad ON auth_user.cai (localidad);
CREATE INDEX IF NOT EXISTS idx_cai_activo ON auth_user.cai (activo);

