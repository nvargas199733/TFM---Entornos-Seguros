-- Tabla de Usuarios
CREATE TABLE IF NOT EXISTS auth_user.usuario (
    id_usuario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol bigint NOT NULL REFERENCES auth_user.rol(id_rol),
    cedula varchar(20) NOT NULL UNIQUE,
    nombres varchar(100) NOT NULL,
    apellidos varchar(100) NOT NULL,
    telefono varchar(20),
    correo varchar(120) NOT NULL UNIQUE,
    contrasena_hash varchar(255) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp NOT NULL DEFAULT NOW(),
    created_at timestamp NOT NULL DEFAULT NOW(),
    updated_at timestamp NOT NULL DEFAULT NOW()
);

-- Índices de búsqueda
CREATE INDEX IF NOT EXISTS idx_usuario_correo ON auth_user.usuario (correo);
CREATE INDEX IF NOT EXISTS idx_usuario_cedula ON auth_user.usuario (cedula);
CREATE INDEX IF NOT EXISTS idx_usuario_rol ON auth_user.usuario (id_rol);

