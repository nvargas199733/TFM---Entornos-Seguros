-- 1. Habilitar extensión geoespacial PostGIS
CREATE EXTENSION IF NOT EXISTS postgis;

-- 2. Crear los esquemas de cada microservicio
CREATE SCHEMA IF NOT EXISTS auth_user;
CREATE SCHEMA IF NOT EXISTS incident;
CREATE SCHEMA IF NOT EXISTS police_report;

-- ------------------------------------------------------------------------------
-- Esquema: auth_user
-- ------------------------------------------------------------------------------

-- Tabla de Roles
CREATE TABLE IF NOT EXISTS auth_user.rol (
    id_rol bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(50) NOT NULL UNIQUE,
    descripcion varchar(150),
    created_at timestamp NOT NULL DEFAULT NOW(),
    updated_at timestamp NOT NULL DEFAULT NOW()
);

